const PROGRESS_TRANSLATION_MAP = {
    'مطابق للخطة': 'On Track',
    'متقدم عن الخطة': 'Ahead of Plan',
    'متأخر عن الخطة': 'Behind Plan',
    'On Track': 'مطابق للخطة',
    'Ahead of Plan': 'متقدم عن الخطة',
    'Behind Plan': 'متأخر عن الخطة',
};

export const translateDefaultCurriculumProgress = (value, targetLang) => {
    const trimmed = String(value || '').trim();
    if (!trimmed) {
        return targetLang === 'en' ? 'On Track' : 'مطابق للخطة';
    }
    if (targetLang === 'en') {
        if (['مطابق للخطة', 'متقدم عن الخطة', 'متأخر عن الخطة'].includes(trimmed)) {
            return PROGRESS_TRANSLATION_MAP[trimmed];
        }
        return value;
    }
    if (['On Track', 'Ahead of Plan', 'Behind Plan'].includes(trimmed)) {
        return PROGRESS_TRANSLATION_MAP[trimmed];
    }
    return value;
};

export const getProgressBadgeStyle = (progress) => {
    if (!progress) return '';
    const lower = String(progress).toLowerCase();
    if (lower.includes('متأخر') || lower.includes('behind')) {
        return 'bg-rose-50 text-rose-700 dark:bg-rose-500/15 dark:text-rose-300';
    }
    if (lower.includes('متقدم') || lower.includes('ahead')) {
        return 'bg-indigo-50 text-indigo-700 dark:bg-indigo-500/15 dark:text-indigo-300';
    }
    return 'bg-emerald-50 text-emerald-700 dark:bg-emerald-500/15 dark:text-emerald-300';
};

